"""Audit the archived G_theta estimates against the rotation-null distribution.

The archived anisotropy tensors are the single primary source for G_theta and
for Fig. 4a-c.  The rotation null needs K_R, which is not stored with those
tensors, so it is generated by a separate control refit.  This script records
that provenance explicitly and verifies that the archived estimates lie below
every null draw.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
OUT = ROOT / "results" / "frozen" / "anisotropy"
NULL_PATH = OUT / "anisotropy_null.json"

SOURCES = {
    "Porto": (ROOT / "results/frozen/anisotropy/fo4_fig5_data.npz",
              "Porto_A_C", "Porto_A_U", "Porto_theta_C", "Porto_theta_U"),
    "SF": (ROOT / "results/frozen/anisotropy/fo4_fig5_data.npz",
           "SF_A_C", "SF_A_U", "SF_theta_C", "SF_theta_U"),
    "Chengdu": (ROOT / "results/frozen/anisotropy/chengdu_anisotropy.npz",
                "Chengdu_A_C", "Chengdu_A_U", "Chengdu_theta_C", "Chengdu_theta_U"),
}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    null = json.loads(NULL_PATH.read_text(encoding="utf-8"))
    cities = {}
    for city, (path, ac_key, au_key, tc_key, tu_key) in SOURCES.items():
        z = np.load(path)
        ac, au = z[ac_key], z[au_key]
        tc, tu = z[tc_key], z[tu_key]
        w = ac * au
        ok = w > 0
        g = float((w[ok] * np.cos(2 * (tc[ok] - tu[ok]))).sum() / w[ok].sum())
        null_draws = np.asarray(null["cities"][city]["G_null"], dtype=float)
        n_above = int((null_draws >= g).sum())
        cities[city] = {
            "source": str(path.relative_to(ROOT)).replace("\\", "/"),
            "source_sha256": sha256(path),
            "estimator": "archived five-fold/consensus tensors"
            if city == "SF" else "archived frozen tensors",
            "n_cells": int(ok.sum()),
            "n_cells_total": int(ac.size),
            "G_theta": g,
            "null_n": int(null_draws.size),
            "null_min": float(null_draws.min()),
            "null_median": float(np.median(null_draws)),
            "null_n_at_least_observed": n_above,
            "one_sided_p": float((1 + n_above) / (1 + null_draws.size)),
            "control_implementation_G": null["cities"][city]["G_theta"],
        }

    payload = {
        "definition": "G_theta = sum_c A_C A_U cos(2(theta_C-theta_U)) / sum_c A_C A_U, A_C A_U > 0",
        "primary_rule": (
            "The archived tensors are the single primary estimate used in the main text, "
            "Supplementary Note S8, and Fig. 4a-c. The control refit supplies only the "
            "spectrum-matched rotation null because K_R is not stored with the archived tensors; "
            "its own G_theta is an implementation check, not a second estimate."
        ),
        "null_source": "results/frozen/anisotropy/anisotropy_null.json",
        "null_source_sha256": sha256(NULL_PATH),
        "cities": cities,
    }
    out = OUT / "gtheta_provenance.json"
    out.write_text(json.dumps(payload, indent=1), encoding="utf-8")
    print(json.dumps(cities, indent=1))
    print("wrote", out)


if __name__ == "__main__":
    main()
