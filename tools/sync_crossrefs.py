from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper" / "merged_manuscript"


def aux_labels(path: Path) -> dict[str, str]:
    if not path.is_file():
        raise FileNotFoundError(f"compile first to generate {path}")
    text = path.read_text(encoding="utf-8", errors="replace")
    return dict(re.findall(r"\\newlabel\{([^}]+)\}\{\{([^}]+)\}", text))


def write_macro_file(path: Path, command: str, labels: dict[str, str]) -> None:
    lines = ["% Auto-generated by tools/sync_crossrefs.py; do not edit manually.",
             "\\makeatletter",
             f"\\newcommand{{\\{command}}}[1]{{\\csname {command}@#1\\endcsname}}"]
    for key in sorted(labels):
        value = labels[key].replace("}", "").replace("{", "")
        lines.append(f"\\expandafter\\newcommand\\csname {command}@{key}\\endcsname{{{value}}}")
    lines.append("\\makeatother")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def replace_refs(path: Path, external_prefix: str, command: str) -> int:
    text = path.read_text(encoding="utf-8")
    keys = sorted(set(re.findall(r"\\ref\{(" + re.escape(external_prefix) + r"[^}]+)\}", text)))
    updated = text.replace(f"\\ref{{{external_prefix}", f"\\{command}{{")
    if updated != text:
        path.write_text(updated, encoding="utf-8")
    return len(keys)


def remove_line(text: str, needle: str) -> str:
    return "\n".join(line for line in text.splitlines() if needle not in line) + "\n"


def main() -> None:
    main_tex = PAPER / "main.tex"
    supplement_tex = PAPER / "supplement.tex"
    main_labels = aux_labels(PAPER / "main.aux")
    supplement_labels = aux_labels(PAPER / "supplement.aux")
    main_external = set(re.findall(r"\\ref\{(sup-[^}]+)\}", main_tex.read_text(encoding="utf-8")))
    supplement_external = set()
    for path in [supplement_tex, *sorted((PAPER / "supplement_sections").glob("*.tex"))]:
        supplement_external.update(re.findall(r"\\ref\{(main-[^}]+)\}", path.read_text(encoding="utf-8")))
    missing = sorted(set(main_external) - {"sup-" + key for key in supplement_labels} |
                     set(supplement_external) - {"main-" + key for key in main_labels})
    if missing:
        raise RuntimeError(f"external labels missing from aux: {missing}")
    write_macro_file(PAPER / "main_refs.tex", "MainRef", main_labels)
    write_macro_file(PAPER / "supplement_refs.tex", "SuppRef", supplement_labels)

    main_count = replace_refs(main_tex, "sup-", "SuppRef")
    supplement_count = 0
    for path in [supplement_tex, *sorted((PAPER / "supplement_sections").glob("*.tex"))]:
        supplement_count += replace_refs(path, "main-", "MainRef")

    for path, external, generated in [(main_tex, "supplement", "supplement_refs"),
                                      (supplement_tex, "main", "main_refs")]:
        text = path.read_text(encoding="utf-8")
        text = remove_line(text, "\\usepackage{xr}")
        text = remove_line(text, "\\externaldocument")
        marker = "\\hypersetup"
        if f"\\input{{{generated}}}" not in text:
            text = text.replace(marker, f"\\input{{{generated}}}\n{marker}", 1)
        path.write_text(text, encoding="utf-8")

    remaining = []
    for path in [main_tex, supplement_tex, *sorted((PAPER / "supplement_sections").glob("*.tex"))]:
        text = path.read_text(encoding="utf-8")
        remaining.extend(re.findall(r"\\ref\{(?:sup-|main-)[^}]*\}", text))
    if remaining:
        raise RuntimeError(f"unresolved external refs remain: {remaining}")
    print(f"generated main_refs.tex and supplement_refs.tex; external refs: main={main_count}, supplement={supplement_count}")


if __name__ == "__main__":
    main()
